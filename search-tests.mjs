import assert from 'node:assert/strict';
import {demo,calculate} from './dist/modules/model.js';
import {matches,searchDepartures} from './dist/modules/search.js';
const p=demo(),base={start:'2026-10-20T12:00',end:'2026-10-20T12:10',step:5,leg:'all',minElevation:0,maxElevation:90,fov:'any',reference:'none',maxAngle:180,minimum:0};
const r=await searchDepartures(p,base),schedule=calculate(p);
assert.equal(r.count,3);assert.equal(r.results.length,3);
assert.ok(Math.abs(r.results[0].total-schedule.legs.reduce((s,l)=>s+l.end-l.start,0))<1);
assert.equal(r.results[0].windows.length,2);
const single=await searchDepartures(p,{...base,leg:'1'});assert.ok(single.results.every(x=>x.windows.every(w=>w.legs.join(',')==='2')));
const night=await searchDepartures(p,{...base,start:'2026-10-20T00:00',end:'2026-10-20T00:10'});assert.equal(night.results.length,0);
assert.equal(matches({elevation:10,inFov:true,shipRelative:60,cameraRelative:0},{...base,fov:'inside',reference:'ship',maxAngle:45}),false);
await assert.rejects(()=>searchDepartures(p,{...base,step:0}));
await assert.rejects(()=>searchDepartures(p,base,{cancelled:()=>true}),/取消/);
assert.equal(p.departure,'2026-10-20T08:00');
console.log('PASS: candidate grid, duration conservation, stop gaps, leg filter, night, constraints, validation, cancellation, immutable project');
