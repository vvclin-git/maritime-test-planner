import assert from 'node:assert/strict';
import {distance,bearing,solar,illumination} from './dist/modules/geometry.js';
import {demo,calculate,pointAt,validate} from './dist/modules/model.js';
assert.ok(Math.abs(distance({lat:0,lng:0},{lat:0,lng:1})-111195)<5);
assert.equal(bearing({lat:0,lng:0},{lat:0,lng:1}),90);
let p=demo(),r=calculate(p);assert.equal(r.legs.length,3);assert.equal(r.legs[1].start-r.arrivals[1],300000);
assert.ok(Math.abs(r.end-r.start-r.legs.reduce((s,l)=>s+l.length/(l.speed*.514444)*1000,0)-300000)<1);
assert.equal(pointAt(p,r,r.arrivals[1]+1000).waiting,true);
const sun=solar(Date.parse('2026-03-20T12:00:00Z'),0,0);assert.ok(sun.elevation>87);
assert.equal(illumination({azimuth:90,elevation:20},90,{yaw:0,pitch:20,hfov:60,vfov:30}).inFov,true);
assert.equal(illumination({azimuth:270,elevation:20},90,{yaw:0,pitch:20,hfov:60,vfov:30}).inFov,false);
p.segments[0].speed=0;assert.throws(()=>validate(p));
p=demo();p.sampleMode='time';p.sampleStep=60;r=calculate(p);assert.equal(r.samples[1].time-r.samples[0].time,60000);
console.log('PASS: geodesy, time model, waits, solar reference, 3D FOV, validation, sampling');
